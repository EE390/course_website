LCD_SECOND_LINE_C:
	CLR RS
	MOV LCD_DATA,#0CCH ; Force LCD cursor to the 2nd line 13th character
	LCALL SEND_LCD_DATA
	SETB RS
	RET
	
LCD_SECOND_LINE:
	CLR RS
	MOV LCD_DATA,#0C0H ; Force cursor to the beginning ( 2nd line)
	LCALL SEND_LCD_DATA
	SETB RS
	RET
	
TEXT_INTRO:             DB '   EEPROM  R/W  ',00H
